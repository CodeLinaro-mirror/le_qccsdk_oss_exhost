uint8_t atcmd_response_handler(uint16_t buf_len, char * cmd) {
	int argc;
	char * argv[AT_ARGC_MAX]={0};
	char *p;
	int comma_found=0;
	int func_found=0;
	// Separating header and arguments
	char header[AT_CMD_MAX_SIZE] = "";
	int i = 0;
	int h = 0;
	int arg_start = 0;

	for (i=0;i<buf_len;i++)
	{
		if (cmd[i] == '\r' || cmd[i] == '\0' || cmd[i] == '\n')
		{
			continue;
		}
		if (cmd[i] == ':')
		{
			break;
		}
		header[h] = cmd[i];
		h++;
	}
	header[h] = '\0';
	arg_start = i;
	// Searching for the command and parameters
	if(0 == cmd_shell_find_command_index(&i, header, h))
	{
		printf("Response before parsing:\r\n");
		printf("%s\r\n", cmd);

		argc = 1;
		cmd += arg_start+1;
		argv[0] = cmd;
		func_found = 1;
		for(p = cmd ; *p != '\0' && argc < AT_ARGC_MAX ; p++)
		{
			if(*p == '\r')
			{
				if(*(p+1) == '\n')
				{
					*p = '\0';
					p++;
				}
				*p = '\0';
				argv[argc] = p+1;
			}
			else if(*p == ',') {
				*p = '\0';
				argv[argc] = p+1;
				argc++;
			}
			else {
				;
			}
		}
		printf("Response after parsing:\r\n");
		return cmd_shell_exec_function_by_index(argc, argv, i);
	}
	else
	{
		printf("%s\r\n", cmd);
		return 0;
	}
	
	return -1;
}

void qcc730_atcmd_send_handler(uint8_t *cmd, uint32_t len)
{
	struct device_id id = {0};
    uint16_t buf_len = ATCMD_BUF_LEN;	
	int32_t  ret = 0;
	
	if (NULL == cmd || 1 >= len )
    {
        return;
    }
	
    if (QCC730_SPI_NOT_READY == qapi_atcmd_get_spi_state())
    {   
	    qapi_spi_get_slaveid(&id);
	    if(id.array[1]!=QCSPI_ID1 || id.array[2]!=QCSPI_ID2)
	    {
			return;	        
	    }
			
    	if (0 != qapi_spi_ring_init())
    	{
    	    printf("qcspi init failed, please try it again!\r\n");
			return;
    	}
    }

    qapi_atcmd_send(cmd, len);

}

void qcc730_atcmd_recv_callback(uint8_t *data, uint32_t len)
{    
	if(qat_demo_parser_enable == 0)
		printf("%s", data);
	else
		atcmd_response_handler(len, data);
}

